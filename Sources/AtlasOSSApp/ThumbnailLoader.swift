import AppKit
import AtlasCore
import Foundation

/// Everything a cell needs to ask for pixels.
///
/// A plain value so the decode work can cross a task boundary without dragging the view
/// (or the `@MainActor` model) along with it.
struct ThumbnailRequest: Hashable, Sendable {
    /// Library identity of the content. Two items with the same bytes share one thumbnail.
    let contentHash: String
    /// The file to generate from — `originals/<storedName>` for copies, the linked path
    /// for connected items.
    let sourceURL: URL?
    /// `<library>/thumbnails`. `nil` disables the disk tier (previews, tests, an unopened
    /// library) and falls back to the pre-P1f behaviour of downsampling the original.
    let thumbnailsRoot: URL?

    init(contentHash: String, sourceURL: URL?, thumbnailsRoot: URL?) {
        self.contentHash = contentHash
        self.sourceURL = sourceURL
        self.thumbnailsRoot = thumbnailsRoot
    }

    init(item: AtlasCore.LibraryItem, sourceURL: URL?, thumbnailsRoot: URL?) {
        self.init(contentHash: item.contentHash, sourceURL: sourceURL, thumbnailsRoot: thumbnailsRoot)
    }
}

/// Two-tier thumbnail loader: **disk first, memory in front of it, original last.**
///
/// P1f shape, after the Nuke / digiKam reading:
///
/// | Tier | Holds | Cost on hit | Why |
/// |---|---|---|---|
/// | memory | decoded `NSImage`, LRU-bounded | ~0 | scrolling back over seen tiles |
/// | disk (`AtlasCore.ThumbnailStore`) | JPEG per (content hash, bucket) | one small decode | survives relaunch; never inside the cell render |
/// | original | the user's file | expensive | only when the disk tier is off or failed |
///
/// The rule the grid depends on: **when a thumbnail exists, the original URL is never
/// handed to the decoder.** A cell that scrolls into view asks this loader, which asks the
/// store, which answers with a `stat`-priced hit.
///
/// Generation and decoding happen in a utility-priority task, so nothing here blocks the
/// main actor; the `@MainActor` hop covers only the memory-cache check and the final
/// `NSImage` construction.
@MainActor
final class ThumbnailLoader {

    /// The app uses one loader so the memory cache is shared by the grid, the Info preview
    /// and the lightbox. Tests build their own to keep caches isolated.
    static let shared = ThumbnailLoader()

    /// 512 tiles ≈ four full screens at default density: enough that scrolling back is
    /// free without pinning an entire 10k library in RAM.
    static let memoryCountLimit = 512
    /// ~96 MB of decoded pixels. At 360 px buckets a tile is ≈0.5 MB, so the count limit
    /// normally bites first; this is the backstop for oversized (540 px) tiles.
    static let memoryCostLimit = 96 << 20

    private let memory = LRUCache<String, NSImage>(
        countLimit: ThumbnailLoader.memoryCountLimit,
        costLimit: ThumbnailLoader.memoryCostLimit
    )

    /// Which tier answered. Only used for the statistics block.
    enum Tier: Sendable, Equatable {
        /// A thumbnail that was already on disk.
        case diskHit
        /// A thumbnail generated by this call.
        case diskGenerated
        /// No disk tier / generation failed → the original had to be decoded.
        case original
        case failed
    }

    struct DecodeResult {
        let image: CGImage?
        let tier: Tier
    }

    /// One in-flight decode per key: a viewport full of cells showing the same item, or a
    /// double-click that re-realises a cell, produces one generation, not N.
    private var inFlight: [String: Task<DecodeResult, Never>] = [:]

    private(set) var diskHits = 0
    private(set) var diskMisses = 0
    private(set) var originalFallbacks = 0
    private(set) var memoryHits = 0
    private(set) var coalescedRuns = 0
    /// JPEG encodes actually performed. Counted once per *generation*, not per cell, so
    /// `generations == 0` on a warm pass proves nothing was re-encoded.
    private(set) var generations = 0

    init() {}

    // MARK: - Public surface

    func image(for request: ThumbnailRequest, maxPixel: Int) async -> NSImage? {
        let bucket = ThumbnailStore.bucket(forMaxPixel: maxPixel)
        let key = request.contentHash + "#" + String(bucket)

        if let cached = memory.value(forKey: key) {
            memoryHits += 1
            return cached
        }

        guard let cgImage = await decode(request, bucket: bucket, key: key) else { return nil }
        let image = NSImage(
            cgImage: cgImage,
            size: NSSize(width: cgImage.width, height: cgImage.height)
        )
        memory.insert(image, forKey: key, cost: cgImage.bytesPerRow * cgImage.height)
        return image
    }

    /// Single-file, non-grid preview (Info panel, lightbox). Reads the original — these are
    /// one-at-a-time and quality matters more than latency — with the same memory cache in
    /// front so stepping through the lightbox does not re-decode.
    static func thumbnail(for url: URL, maxPixelSize: Int) async -> NSImage? {
        await shared.image(
            for: ThumbnailRequest(contentHash: url.path, sourceURL: url, thumbnailsRoot: nil),
            maxPixel: maxPixelSize
        )
    }

    struct Statistics: Sendable, Equatable {
        var diskHits = 0
        var diskMisses = 0
        var originalFallbacks = 0
        var memoryHits = 0
        var coalescedRuns = 0
        var generations = 0
        var cachedImages = 0
        var cachedBytes = 0
    }

    func statistics() -> Statistics {
        Statistics(
            diskHits: diskHits,
            diskMisses: diskMisses,
            originalFallbacks: originalFallbacks,
            memoryHits: memoryHits,
            coalescedRuns: coalescedRuns,
            generations: generations,
            cachedImages: memory.count,
            cachedBytes: memory.currentCost
        )
    }

    func resetStatistics() {
        diskHits = 0
        diskMisses = 0
        originalFallbacks = 0
        memoryHits = 0
        coalescedRuns = 0
        generations = 0
    }

    func purgeMemoryCache() {
        memory.removeAll()
    }

    // MARK: - Decode

    private func decode(_ request: ThumbnailRequest, bucket: Int, key: String) async -> CGImage? {
        let task: Task<DecodeResult, Never>
        let startedHere: Bool
        if let existing = inFlight[key] {
            coalescedRuns += 1
            startedHere = false
            task = existing
        } else {
            task = Task.detached(priority: .utility) {
                ThumbnailLoader.produce(request, bucket: bucket)
            }
            inFlight[key] = task
            startedHere = true
        }

        let result = await task.value
        inFlight[key] = nil

        // Only the cell that *started* the run counts it, so a stampede of N cells over one
        // item reports one generation rather than N.
        if startedHere, result.tier == .diskGenerated { generations += 1 }

        switch result.tier {
        case .diskHit: diskHits += 1
        case .diskGenerated: diskMisses += 1
        case .original: originalFallbacks += 1
        case .failed: break
        }
        return result.image
    }

    /// Runs on a background thread. Disk tier first, original only as a fallback.
    private nonisolated static func produce(_ request: ThumbnailRequest, bucket: Int) -> DecodeResult {
        if let root = request.thumbnailsRoot,
           ThumbnailStore.isDiskBacked(maxPixel: bucket),
           let source = request.sourceURL {
            let store = ThumbnailStore(root: root)
            let hadFile = store.existingURL(forContentHash: request.contentHash, maxPixel: bucket) != nil
            if let url = try? store.ensure(
                contentHash: request.contentHash,
                maxPixel: bucket,
                sourceURL: source
            ), let image = ThumbnailStore.downsample(url: url, maxPixel: bucket) {
                return DecodeResult(image: image, tier: hadFile ? .diskHit : .diskGenerated)
            }

            // The source is gone or unreadable (unmounted volume, moved file, a video). A
            // thumbnail that already exists is still the best answer — showing the last
            // known frame beats a broken tile, and it is the *cheap* path either way.
            if hadFile,
               let staleURL = store.existingURL(forContentHash: request.contentHash, maxPixel: bucket),
               let cached = ThumbnailStore.downsample(url: staleURL, maxPixel: bucket) {
                return DecodeResult(image: cached, tier: .diskHit)
            }
        }

        // No disk tier, or nothing on disk to serve: fall back to the original so the cell
        // is not blank. This is precisely the path P1f exists to keep off the hot path —
        // `statistics().originalFallbacks` counts how often it actually runs.
        guard let source = request.sourceURL,
              let image = ThumbnailStore.downsample(url: source, maxPixel: bucket) else {
            return DecodeResult(image: nil, tier: .failed)
        }
        return DecodeResult(image: image, tier: .original)
    }
}
